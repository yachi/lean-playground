"""Generate the kernel certificate tables for `ThirdConjectureMulti.lean`.

Usage: python3 gen_tables.py OUTDIR p1 p2 ...   (needs python-flint)

For each prime p, one entry per class of (a², b², c²) mod p up to nonzero squares and
swapping a, b (keyed by `normKey`, as in `ThirdConjectureCert.lean`) whose degree pattern is
informative (subset sums ≠ {0, …, 12}). Each entry stores the factorization of the cuboid
polynomial at a representative, with irreducibility certificates (`certB`).
"""
import sys, itertools, flint

def coeffs(p, A, B, C):
    Z = [C**2*A**2*B**2, 0, 6*A**2*C*B**2-2*C**2*A**2*B-2*C**2*A*B**2, 0,
         4*C*B**2*A+4*A**2*C*B-12*C**2*A*B+C**2*A**2+C**2*B**2+A**2*B**2, 0,
         6*A**2*C+6*C*B**2-8*A*B*C-2*C**2*A-2*C**2*B-2*A**2*B-2*B**2*A, 0,
         C**2+B**2+A**2+4*A*C+4*B*C-12*B*A, 0, 6*C-2*A-2*B, 0, 1]
    return [z % p for z in Z]

def sums(degs):
    s = {0}
    for d in degs:
        s |= {x + d for x in s}
    return s

def inv(p, a): return pow(a, p - 2, p)

def norm_key(p, A, B, C):
    if C != 0:
        u = inv(p, C); x = A*u % p; y = B*u % p
        return (min(x, y), max(x, y), 1)
    if A == 0: return (0, 0 if B == 0 else 1, 0)
    if B == 0: return (0, 1, 0)
    return (min(A*inv(p, B) % p, B*inv(p, A) % p), 1, 0)

def L(f):
    c = [int(x) for x in f.coeffs()]
    return c if c else [0]

def cert(H, p):
    h = L(H); n = len(h) - 1
    if n == 1: return [h]
    P = lambda l: flint.nmod_poly(l, p)
    X = P([0, 1])
    q0, m1 = divmod(P([0]*p + [1]), H)
    rec = [h, L(m1), L(q0)]
    ms = [P([1]), m1]; prev = m1
    for i in range(2, n):
        q, m = divmod(prev*m1, H)
        rec += [L(m), L(q)]; ms.append(m); prev = m
    r = X
    for k in range(1, n//2 + 1):
        cs = [int(x) for x in r.coeffs()]
        assert len(cs) <= len(ms)
        r = sum((P([c])*ms[i] for i, c in enumerate(cs)), P([0]))
        d, s, t = H.xgcd(r - X)
        assert d == 1
        rec += [L(s), L(t)]
    return rec

def table(p):
    sq = sorted({x*x % p for x in range(p)})
    root = {x*x % p: x for x in range(p - 1, -1, -1)}
    keys = {}
    for A, B, C in itertools.product(sq, repeat=3):
        k = norm_key(p, A, B, C)
        keys.setdefault(k, (A, B, C))
    out = []
    for k in sorted(keys):
        r = tuple(root[x] for x in k)
        f = flint.nmod_poly(coeffs(p, r[0]**2 % p, r[1]**2 % p, r[2]**2 % p), p)
        _, fac = f.factor()
        degs = [g.degree() for g, e in fac for _ in range(e)]
        if sums(degs) == set(range(13)):
            continue
        recs = [cert(g, p) for g, e in fac for _ in range(e)]
        out.append((k, r, degs, recs))
    return out

def lean_list(x):
    if isinstance(x, (list, tuple)) and not isinstance(x, tuple):
        return "[" + ", ".join(lean_list(y) for y in x) + "]"
    if isinstance(x, tuple):
        return "(" + ", ".join(lean_list(y) for y in x) + ")"
    return str(x)

CHUNK = 12

def write(outdir, p, tab):
    lines = [f"""module

public import LeanPlayground.PerfectCuboid.ThirdConjectureCert

/-!
# Certified degree patterns of the third cuboid polynomial modulo `{p}`

Generated by `scripts/third_cuboid/gen_tables.py`: {len(tab)} classes of `(a², b², c²)` modulo `{p}`
(up to nonzero squares and swapping `a, b`) with an informative degree pattern, each with the
factorization of `cuboidThreePoly` at a representative and irreducibility certificates (`certB`).
-/

@[expose] public section

namespace PerfectCuboid.ThirdConjecture.ModP.Tables

set_option maxRecDepth 100000
set_option linter.style.longLine false
set_option linter.style.setOption false
"""]
    names = []
    for i in range(0, len(tab), CHUNK):
        nm = f"t{p}_{i // CHUNK}"; names.append(nm)
        body = ",\n  ".join("(" + lean_list(k) + ", " + lean_list(r) + ", " + lean_list(recs) + ")"
                            for k, r, _, recs in tab[i:i+CHUNK])
        lines.append(f"/-- Classes modulo `{p}`, part {i // CHUNK}. -/\ndef {nm} : List Entry := [\n  {body}]\n\n"
                     f"theorem {nm}_ok : {nm}.all (entryOK {p}) = true := by decide +kernel\n")
    lines.append(f"/-- All certified classes modulo `{p}`. -/\ndef table{p} : List Entry :=\n  "
                 + " ++ ".join(names) + "\n")
    if len(names) == 1:
        lines.append(f"theorem table{p}_ok : table{p}.all (entryOK {p}) = true := {names[0]}_ok\n")
    else:
        lines.append(f"theorem table{p}_ok : table{p}.all (entryOK {p}) = true := by\n  simp only [table{p}, List.all_append, "
                     + ", ".join(n + "_ok" for n in names) + ", Bool.and_self]\n")
    lines.append("end PerfectCuboid.ThirdConjecture.ModP.Tables\n")
    open(f"{outdir}/T{p}.lean", "w").write("\n".join(lines))

if __name__ == "__main__":
    outdir = sys.argv[1]
    for p in map(int, sys.argv[2:]):
        tab = table(p)
        write(outdir, p, tab)
        print(p, len(tab), "entries")
